#!/usr/bin/env python3
"""
Тест для проверки упрощенной системы памяти в аудиорежиме
"""

import requests

def test_simplified_memory():
    """Тестирует упрощенную систему памяти для аудиорежима"""
    
    print("🎵 Тестирование упрощенной системы памяти")
    print("=" * 50)
    
    # Проверяем, что сервер работает
    try:
        response = requests.get("http://localhost:31337/memories/stats")
        stats = response.json()
        print(f"✅ Сервер работает. Воспоминаний в БД: {stats['total_memories']}")
    except Exception as e:
        print(f"❌ Сервер не отвечает: {e}")
        return
    
    print("\n🔧 Упрощенная система памяти:")
    print("   - Загружаем только воспоминания этого дня")
    print("   - Никаких периодических обновлений")
    print("   - Никаких прерываний речи")
    print("   - Плавные аудиоответы")
    
    print("\n📋 Как это работает:")
    print("1. При запуске live режима загружаются воспоминания этого дня")
    print("2. Ингрия получает контекст один раз в начале сессии")
    print("3. Новые воспоминания сохраняются, но не добавляются в контекст")
    print("4. Аудиоответы плавные, без прерываний")
    
    print("\n✅ Преимущества:")
    print("   - Плавные аудиоответы")
    print("   - Нет прерываний речи")
    print("   - Простая и надежная система")
    print("   - Ингрия помнит события этого дня")
    
    print("\n🚀 Готово к тестированию!")
    print("Запустите: python live.py --user-id 1")

if __name__ == "__main__":
    test_simplified_memory() 